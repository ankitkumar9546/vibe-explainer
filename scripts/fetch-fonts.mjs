// Download the console's fonts (latin subset, woff2) into packages/console/fonts.
// All three are under the SIL Open Font License 1.1 (see packages/console/fonts/OFL.txt).
// Run: node scripts/fetch-fonts.mjs
import fs from "node:fs";
import path from "node:path";

const OUT = path.resolve("packages/console/fonts");
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const FAMILIES = "family=Baloo+2:wght@600;700;800&family=Nunito:ital,wght@0,400;0,600;0,700;0,800;1,400&family=JetBrains+Mono:wght@400;600";

fs.mkdirSync(OUT, { recursive: true });
const css = await (await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`, { headers: { "user-agent": UA } })).text();
let outCss = "/* Self-hosted fonts (SIL OFL 1.1). Generated by scripts/fetch-fonts.mjs */\n";
for (const block of css.split("}").map((b) => b.trim()).filter(Boolean)) {
  if (!/\/\* latin \*\//.test(block) && !block.startsWith("/* latin */")) {
    // keep only the latin subset blocks
    const label = block.match(/\/\*\s*([\w-]+)\s*\*\//)?.[1];
    if (label !== "latin") continue;
  }
  const fam = block.match(/font-family:\s*'([^']+)'/)[1];
  const weight = block.match(/font-weight:\s*(\d+)/)[1];
  const style = block.match(/font-style:\s*(\w+)/)[1];
  const url = block.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const name = `${fam.replace(/\s+/g, "")}-${weight}${style === "italic" ? "i" : ""}.woff2`;
  fs.writeFileSync(path.join(OUT, name), Buffer.from(await (await fetch(url)).arrayBuffer()));
  outCss += `@font-face{font-family:'${fam}';font-style:${style};font-weight:${weight};font-display:swap;src:url(fonts/${name}) format('woff2')}\n`;
  console.log(name);
}
fs.writeFileSync(path.join(path.dirname(OUT), "fonts.css"), outCss);
